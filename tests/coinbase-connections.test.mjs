import assert from 'node:assert/strict';
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import test from 'node:test';
import { _electron as electron } from 'playwright-core';
import executablePath from 'electron';
import { stopHost } from './helpers/host.mjs';

test('Coinbase guided import and account management work without a Robinhood connection', { timeout: 40000 }, async () => {
  const profile = await mkdtemp(join(tmpdir(), 'earlybird-coinbase-ui-'));
  const droppedKey = join(profile, 'synthetic-key.json');
  await writeFile(droppedKey, '{}');
  let application;
  try {
    const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE; delete env.ELECTRON_RENDERER_URL;
    application = await electron.launch({ executablePath, args: ['.', '--earlybird-test-no-secrets', `--user-data-dir=${profile}`], env });
    const page = await application.firstWindow(); page.setDefaultTimeout(7000);
    await page.getByRole('dialog', { name: 'Connect a trading platform' }).waitFor();
    await application.evaluate(({ ipcMain, shell }) => {
      globalThis.coinbaseOpenedUrls = [];
      shell.openExternal = async url => { globalThis.coinbaseOpenedUrls.push(url); };
      let items = []; let attempt = 0;
      const result = () => ({ ok: true, connections: items });
      for (const name of ['list', 'import-key', 'import-progress', 'import-dropped-key', 'rename', 'disconnect']) ipcMain.removeHandler(`coinbase:${name}`);
      ipcMain.handle('coinbase:list', result);
      ipcMain.handle('coinbase:import-dropped-key', (_event, path, options) => { globalThis.coinbaseDropped = { path, options }; return { ok: true, cancelled: true, connections: items }; });
      ipcMain.handle('coinbase:import-progress', () => globalThis.coinbaseTestStage ?? null);
      ipcMain.handle('coinbase:import-key', async (_event, options) => {
        if (Object.keys(options).some(key => !['connectionId', 'label', 'readOnly'].includes(key))) throw Error('Unexpected import payload');
        if (++attempt === 1) return { ok: false, message: 'Synthetic permission rejection.' };
        if (attempt === 2) { globalThis.coinbaseTestStage = 'portfolio'; await new Promise(resolve => { globalThis.finishCoinbaseImport = resolve; }); globalThis.coinbaseTestStage = null; }
        items.push({ connectionId: `connection-${attempt}`, accountId: `account-${attempt}`, venue: 'coinbase', environment: 'live', label: attempt === 2 ? 'Main Coinbase' : 'Savings Coinbase', portfolioName: attempt === 2 ? 'Primary' : 'Savings', maskedReference: '••••1234', status: 'connected', checkedAt: null, permissions: { view: true, trade: !options.readOnly, transfer: false }, capabilities: { accountRead: true, chat: false, trading: false } });
        return result();
      });
      ipcMain.handle('coinbase:rename', (_event, id, label) => { items = items.map(item => item.connectionId === id ? { ...item, label } : item); return result(); });
      ipcMain.handle('coinbase:disconnect', (_event, id) => { items = items.map(item => item.connectionId === id ? { ...item, status: 'disconnected' } : item); return result(); });
    });
    await page.reload();
    const prompt = page.getByRole('dialog', { name: 'Connect a trading platform' });
    const section = prompt.getByRole('region', { name: 'Coinbase connections' });
    await section.getByRole('button', { name: 'Connect', exact: true }).click();
    const setup = page.getByRole('dialog', { name: 'Connect Coinbase', exact: true });
    await setup.getByRole('button', { name: /Connect my existing portfolio/ }).waitFor();
    if (process.env.COINBASE_PREVIEW) await setup.screenshot({ path: '/tmp/coinbase-wizard-start.png' });
    await setup.getByRole('button', { name: 'Back', exact: true }).click();
    await setup.waitFor({ state: 'hidden' });
    await section.getByRole('button', { name: 'Connect', exact: true }).click();
    await setup.getByRole('button', { name: /Create a separate portfolio/ }).click();
    const portfolio = page.getByRole('dialog', { name: 'Create a separate portfolio', exact: true });
    await portfolio.getByText('Open Coinbase Advanced, then Portfolio › Spot').waitFor();
    await portfolio.getByText('Step 1 of 3 · On Coinbase').waitFor();
    await portfolio.getByText('Open the portfolio menu and pick New portfolio').waitFor();
    await portfolio.getByText('See Coinbase screenshot', { exact: true }).click();
    const guide = portfolio.getByRole('img', { name: /Coinbase Advanced Portfolio page/ });
    await guide.waitFor();
    assert.equal(await guide.evaluate(image => image.complete && image.naturalWidth > 0), true);
    await portfolio.getByText('See Coinbase screenshot', { exact: true }).click();
    if (process.env.COINBASE_PREVIEW) await portfolio.screenshot({ path: '/tmp/coinbase-wizard-portfolio.png' });
    await portfolio.getByRole('button', { name: 'Open Coinbase Advanced', exact: true }).click();
    assert.deepEqual(await application.evaluate(() => globalThis.coinbaseOpenedUrls), ['https://www.coinbase.com/advanced-portfolio']);
    await portfolio.getByRole('button', { name: 'I’ve created my portfolio' }).click();
    const key = page.getByRole('dialog', { name: 'Create your API key', exact: true });
    await key.getByText('Select the portfolio from step 1').waitFor();
    await key.getByText('Step 2 of 3 · On Coinbase').waitFor();
    if (process.env.COINBASE_PREVIEW) await key.screenshot({ path: '/tmp/coinbase-redesign-key.png' });
    await key.getByRole('button', { name: 'Back', exact: true }).click();
    await portfolio.getByRole('button', { name: 'Back', exact: true }).click();
    await setup.getByRole('button', { name: /Connect my existing portfolio/ }).click();
    await key.getByText('ECDSA', { exact: true }).waitFor();
    await key.getByRole('button', { name: 'Open Coinbase key settings', exact: true }).click();
    assert.deepEqual(await application.evaluate(() => globalThis.coinbaseOpenedUrls), ['https://www.coinbase.com/advanced-portfolio', 'https://portal.cdp.coinbase.com/api-keys/secret']);
    if (process.env.COINBASE_PREVIEW) await key.screenshot({ path: '/tmp/coinbase-wizard-key.png' });
    await key.getByRole('button', { name: 'I’ve downloaded my key' }).click();
    const importer = page.getByRole('dialog', { name: 'Import your key', exact: true });
    assert.equal(await importer.getByRole('textbox').count(), 0);
    await importer.getByText('Step 2 of 2 · Back in Opentake').waitFor();
    if (process.env.COINBASE_PREVIEW) await importer.screenshot({ path: '/tmp/coinbase-redesign-import.png' });
    await importer.getByRole('button', { name: 'Choose JSON file' }).click();
    await importer.getByRole('alert').getByText('Synthetic permission rejection.').waitFor();
    await importer.getByRole('button', { name: 'Choose JSON file' }).click();
    await importer.getByText('Key file is valid', { exact: true }).waitFor();
    await importer.getByText('Find your portfolio', { exact: true }).waitFor();
    assert.equal(await importer.getByRole('button', { name: 'Change', exact: true }).isDisabled(), true);
    if (process.env.COINBASE_PREVIEW) await importer.screenshot({ path: '/tmp/coinbase-redesign-verifying.png' });
    await application.evaluate(() => globalThis.finishCoinbaseImport());
    const success = page.getByRole('dialog', { name: 'You’re connected', exact: true });
    await success.getByText('Primary', { exact: true }).waitFor();
    if (process.env.COINBASE_PREVIEW) await success.screenshot({ path: '/tmp/coinbase-wizard-success.png' });
    await success.getByRole('button', { name: 'Connect another portfolio' }).click();
    await setup.getByRole('button', { name: 'Back', exact: true }).click();
    await page.getByRole('dialog', { name: 'Connections', exact: true }).getByRole('button', { name: 'Close dialog' }).click();
    await page.reload();
    await page.getByRole('button', { name: 'Settings', exact: true }).click();
    assert.equal(await page.getByRole('dialog', { name: 'Connect a trading platform' }).count(), 0);
    await page.getByRole('button', { name: 'Connections', exact: true }).click();
    const settings = page.getByRole('region', { name: 'Coinbase connections' });
    await settings.getByRole('button', { name: 'Add account' }).click();
    await setup.getByRole('button', { name: 'Back', exact: true }).click();
    await setup.waitFor({ state: 'hidden' });
    await settings.getByRole('button', { name: 'Add account' }).click();
    await setup.getByRole('button', { name: /I already have an API key/ }).click();
    await importer.getByRole('button', { name: 'Back', exact: true }).click();
    await setup.getByRole('button', { name: /I already have an API key/ }).click();
    await importer.getByText('Step 1 of 1 · In Opentake').waitFor();
    await page.evaluate(() => { const input = document.createElement('input'); input.type = 'file'; input.id = 'synthetic-drop'; document.body.append(input); });
    await page.locator('#synthetic-drop').setInputFiles(droppedKey);
    await importer.getByText('Drop your key file here', { exact: true }).evaluate(target => {
      const input = document.querySelector('#synthetic-drop'); const data = new DataTransfer(); data.items.add(input.files[0]);
      target.dispatchEvent(new DragEvent('drop', { bubbles: true, cancelable: true, dataTransfer: data })); input.remove();
    });
    await importer.getByRole('button', { name: 'Choose JSON file' }).waitFor();
    assert.deepEqual(await application.evaluate(() => globalThis.coinbaseDropped), { path: droppedKey, options: { connectionId: undefined, readOnly: false } });
    if (process.env.COINBASE_PREVIEW) await importer.screenshot({ path: '/tmp/coinbase-redesign-direct.png' });
    await importer.getByRole('button', { name: 'Change', exact: true }).click();
    await importer.getByRole('radio', { name: /^Read-only/ }).check();
    await importer.getByRole('button', { name: 'Choose JSON file' }).click();
    await success.getByText('Savings', { exact: true }).waitFor();
    await success.getByRole('button', { name: 'Done', exact: true }).click();
    await settings.getByText('Savings Coinbase', { exact: true }).waitFor();
    await settings.getByText(/Read-only/).waitFor();
    await settings.getByRole('button', { name: 'Manage Main Coinbase', exact: true }).click();
    await page.getByRole('menuitem', { name: 'Replace key', exact: true }).waitFor();
    await page.screenshot({path:'/tmp/coinbase-connected-menu.png'});
    await page.getByRole('menuitem', { name: 'Rename', exact: true }).click();
    await settings.getByRole('textbox', { name: 'Connection label' }).fill('Renamed Coinbase');
    await settings.getByRole('button', { name: 'Save', exact: true }).click();
    await settings.getByText('Renamed Coinbase', { exact: true }).waitFor();
    await settings.getByRole('button', { name: 'Manage Renamed Coinbase', exact: true }).click();
    await page.getByRole('menuitem', { name: 'Disconnect', exact: true }).click();
    await settings.getByRole('button', { name: 'Disconnect account', exact: true }).click();
    await settings.getByText('Disconnected', { exact: true }).waitFor();
    assert.equal(await settings.getByText('Connected', { exact: true }).count(), 1);
  } finally { if (application) await application.close(); await stopHost(profile); await rm(profile, { recursive: true, force: true }); }
});
